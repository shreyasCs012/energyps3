"""Export JSON Schema and a small generated TypeScript contract surface."""

import json
from pathlib import Path

from contracts.models import (
    AnomalyEvent,
    AnomalyResponse,
    ControlCommand,
    CopilotRequest,
    CopilotResponse,
    EquipmentState,
    ForecastPoint,
    ForecastResponse,
    KPIComparison,
    KPIResponse,
    KPISet,
    Recommendation,
    RecommendationConstraint,
    RecommendationDecision,
    RecommendationExplanation,
    RecommendationImpact,
    RecommendationInterval,
    RecommendationPlan,
    RecommendationScheduleRequest,
    ReportResponse,
    RunRequest,
    RunResponse,
    TelemetryPoint,
    WhatIfRequest,
    WhatIfResponse,
)

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "contracts" / "json_schema"


def main() -> None:
    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    for model in (
        TelemetryPoint,
        ControlCommand,
        KPISet,
        KPIComparison,
        Recommendation,
        RecommendationConstraint,
        RecommendationImpact,
        RecommendationInterval,
        RecommendationPlan,
        RecommendationExplanation,
        CopilotResponse,
        CopilotRequest,
        RunRequest,
        RunResponse,
        WhatIfRequest,
        WhatIfResponse,
        ForecastPoint,
        ForecastResponse,
        AnomalyEvent,
        AnomalyResponse,
        RecommendationDecision,
        RecommendationScheduleRequest,
        ReportResponse,
        KPIResponse,
    ):
        destination = SCHEMA_DIR / f"{model.__name__}.schema.json"
        schema = json.dumps(model.model_json_schema(), indent=2) + "\n"
        destination.write_text(schema, encoding="utf-8", newline="\n")

    states = " | ".join(json.dumps(item.value) for item in EquipmentState)
    (ROOT / "web" / "src" / "contracts.ts").write_text(
        f"""// Generated by `make schema`; do not edit by hand.
export type EquipmentState = {states};
export interface TelemetryPoint {{
  timestamp: string;
  equipment_id: string;
  power_kw: number;
  state: EquipmentState | null;
  source: string;
}}
export type ControlAction =
  | 'STANDBY' | 'PRE_WARM' | 'LIGHTS_OFF' | 'HVAC_SETBACK' | 'DEFER_JOB';
export interface ControlCommand {{
  command_id: string;
  issued_at: string;
  equipment_id: string;
  action: ControlAction;
  duration_min: number | null;
  rationale: string;
  setpoint_delta_c: number | null;
}}
export interface KPISet {{
  energy_kwh: number;
  peak_15min_kw: number;
  cost_inr: number;
  co2_kg: number;
  idle_waste_kwh: number;
  restarts: number;
  late_jobs: number;
  comfort_violation_min: number;
}}
export interface KPIComparison {{
  predicted: KPISet;
  realized: KPISet;
  absolute_error: Record<string, number>;
}}
export interface RecommendationImpact {{
  energy_kwh: number;
  cost_inr: number;
  co2_kg: number;
  peak_kw: number;
  late_jobs: number;
}}
export interface RecommendationConstraint {{ rule: string; passed: boolean; detail: string; }}
export interface Recommendation {{
  id: string;
  ts: string;
  equipment: string;
  action: ControlAction;
  action_parameters: Record<string, number | string>;
  start: string;
  duration_min: number;
  projected: RecommendationImpact;
  interval: {{ p05: RecommendationImpact; p95: RecommendationImpact }};
  constraints: RecommendationConstraint[];
  confidence: number;
  evidence: Record<string, unknown>;
  revert_if: string[];
}}
export interface RecommendationPlan {{
  mode: 'human' | 'auto';
  recommendations: Recommendation[];
  rejected: Record<string, unknown>[];
}}
export interface RecommendationExplanation {{
  summary: string;
  rationale: string;
  impact: Record<string, string>;
  constraints: string[];
  caveats: string[];
}}
export interface CopilotResponse {{
  tool: 'what_if' | 'get_kpis' | 'list_anomalies' | 'forecast';
  answer: string;
  result: Record<string, unknown>;
}}
export interface CopilotRequest {{
  query: string;
}}
export interface RunRequest {{
  scenario: string;
  seed: number;
  days: number;
  cv_mode: 'oracle' | 'simulated';
}}
export interface RunResponse {{
  scenario: string;
  seed: number;
  days: number;
  synthetic: true;
  output_dir: string;
  manifest: Record<string, unknown>;
}}
export interface KPIResponse extends KPISet {{ synthetic: true; }}
export interface WhatIfRequest {{
  action: ControlCommand;
  horizon_min: number;
  scenario: string | null;
  seed: number;
}}
export interface WhatIfResponse {{
  baseline: KPISet;
  projected: KPISet;
  delta: Record<string, number>;
  seed: number;
  synthetic: true;
}}
export interface ForecastPoint {{
  timestamp: string;
  predicted_kw: number;
}}
export interface ForecastResponse {{
  method: string;
  points: ForecastPoint[];
  synthetic: true;
}}
export interface AnomalyEvent {{
  timestamp: string;
  main_kw: number;
  threshold_kw: number;
  score: number;
  detector: string;
}}
export interface AnomalyResponse {{
  events: AnomalyEvent[];
  synthetic: true;
}}
export interface RecommendationDecision {{
  recommendation_id: string;
  status: 'approved' | 'rejected' | 'scheduled';
  scheduled_for: string | null;
  message: string;
}}
export interface RecommendationScheduleRequest {{ scheduled_for: string; }}
export interface ReportResponse {{
  markdown: string;
  synthetic: true;
}}
""",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main()
